// Command genregions writes the district (시군구) table used to resolve
// region names, from the Ministry of the Interior and Safety's official
// legal-dong code list (행정안전부_행정표준코드_법정동코드,
// https://www.data.go.kr/data/15077871/openapi.do).
//
// It is run by maintainers, not users: the service key must be approved for
// that API. Rerun it after administrative reorganizations:
//
//	DATAGOKR_SERVICE_KEY=... go generate ./providers/datagokr
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"go/format"
	"log"
	"net/url"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/YoungsoonLee/mcp-hub/httpx"
)

const endpoint = "https://apis.data.go.kr/1741000/StanReginCd/getStanReginCdList"

type page struct {
	TotalCount int    `xml:"head>totalCount"`
	ResultCode string `xml:"head>RESULT>resultCode"`
	Rows       []row  `xml:"row"`
}

type row struct {
	RegionCd   string `xml:"region_cd"`
	SggCd      string `xml:"sgg_cd"`
	UmdCd      string `xml:"umd_cd"`
	RiCd       string `xml:"ri_cd"`
	LocataddNm string `xml:"locatadd_nm"`
}

func main() {
	out := flag.String("out", "regions_data.go", "output file")
	flag.Parse()
	key := os.Getenv("DATAGOKR_SERVICE_KEY")
	if key == "" {
		log.Fatal("DATAGOKR_SERVICE_KEY is not set")
	}

	rows, err := fetchAll(context.Background(), key)
	if err != nil {
		log.Fatal(err)
	}

	sidoNames := map[string]string{} // "11" -> 서울특별시
	type district struct{ code, sido, name, parent string }
	var districts []district
	for _, r := range rows {
		if r.UmdCd != "000" || r.RiCd != "00" || len(r.RegionCd) != 10 {
			continue
		}
		code := r.RegionCd[:5]
		if r.SggCd == "000" {
			sidoNames[code[:2]] = strings.TrimSpace(r.LocataddNm)
			continue
		}
		districts = append(districts, district{code: code, name: strings.TrimSpace(r.LocataddNm)})
	}
	byName := map[string]string{} // "41 수원시" -> 41110
	for i := range districts {
		d := &districts[i]
		d.sido = sidoNames[d.code[:2]]
		d.name = strings.TrimSpace(strings.TrimPrefix(d.name, d.sido))
		byName[d.code[:2]+" "+d.name] = d.code
	}
	// A 구 inside a 시 is named "수원시 장안구". The upstream parent code
	// (locathigh_cd) points at the 시 for some cities and at the province for
	// others, so the parent is found by name instead.
	for i := range districts {
		d := &districts[i]
		if city, _, ok := strings.Cut(d.name, " "); ok {
			d.parent = byName[d.code[:2]+" "+city]
		}
	}
	sort.Slice(districts, func(a, b int) bool { return districts[a].code < districts[b].code })
	if len(districts) < 200 {
		log.Fatalf("only %d districts; refusing to write a partial table", len(districts))
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/genregions from the official legal-dong code list on %s. DO NOT EDIT.\n\n", time.Now().Format(time.DateOnly))
	b.WriteString("package datagokr\n\n")
	b.WriteString("var sidoNames = map[string]string{\n")
	sidos := make([]string, 0, len(sidoNames))
	for c := range sidoNames {
		sidos = append(sidos, c)
	}
	sort.Strings(sidos)
	for _, c := range sidos {
		fmt.Fprintf(&b, "%q: %q,\n", c, sidoNames[c])
	}
	b.WriteString("}\n\n// districts lists every 시군구. parent is set for a 구 inside a 시.\nvar districts = []district{\n")
	for _, d := range districts {
		fmt.Fprintf(&b, "{%q, %q, %q},\n", d.code, d.name, d.parent)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d districts in %d provinces to %s", len(districts), len(sidoNames), *out)
}

func fetchAll(ctx context.Context, key string) ([]row, error) {
	c := httpx.New(httpx.WithRetries(3))
	var all []row
	for n := 1; ; n++ {
		q := url.Values{"serviceKey": {key}, "type": {"xml"}, "pageNo": {strconv.Itoa(n)}, "numOfRows": {"1000"}}
		var p page
		if err := c.GetXML(ctx, endpoint, q, nil, &p); err != nil {
			return nil, err
		}
		if p.ResultCode != "INFO-0" {
			return nil, fmt.Errorf("page %d: result code %q", n, p.ResultCode)
		}
		all = append(all, p.Rows...)
		if len(p.Rows) == 0 || len(all) >= p.TotalCount {
			return all, nil
		}
	}
}
